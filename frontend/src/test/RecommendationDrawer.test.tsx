import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { RecommendationDrawer } from '@/pages/RecommendationDrawer';
import { ToastProvider } from '@/components/feedback/Toast';
import { mockPatients } from './fixtures/patients.fixture';

function response(body: unknown, status = 200): Response {
  return {
    ok: status >= 200 && status < 300,
    status,
    statusText: status === 503 ? 'Service Unavailable' : 'OK',
    json: async () => body,
  } as Response;
}

function ruleBasedRecommendation() {
  return {
    recommendation_id: 501,
    patient_id: 'PAT-001',
    recommended_bed_id: 'ICU-01',
    algorithm: 'rule_based',
    reason: 'Compatible ICU bed available',
    status: 'RECOMMENDED',
  };
}

function dqnRecommendation() {
  return {
    recommendation_id: 502,
    patient_id: 'PAT-001',
    recommended_bed_id: 'ICU-01',
    algorithm: 'dqn_safe',
    reason: 'Safety review completed',
    status: 'RECOMMENDED',
    safety: {
      overridden: true,
      rule_triggered: 'acuity_guardrail',
      original_action: 1,
      reason: 'acuity_guardrail',
    },
    q_values: [0.7, 0.4, 0.2, -0.1],
    los_estimate_days: 4.25,
    proposed_action: 1,
    final_action: 0,
    proposed_bed_type: 'STEP_DOWN',
    final_bed_type: 'ICU',
  };
}

function renderDrawer() {
  const queryClient = new QueryClient({
    defaultOptions: { queries: { retry: false }, mutations: { retry: false } },
  });
  return render(
    <QueryClientProvider client={queryClient}>
      <ToastProvider>
        <RecommendationDrawer
          patient={mockPatients[0]!}
          isOpen
          onClose={vi.fn()}
        />
      </ToastProvider>
    </QueryClientProvider>,
  );
}

function mockApi(
  recommendationHandler: (body: { patient_id: string; algorithm: string }) => Promise<Response>,
) {
  const fetchMock = vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
    const url = String(input);
    if (url.endsWith('/beds')) {
      return response({
        beds: [{
          bed_id: 'ICU-01',
          bed_type: 'ICU',
          ward: 'ICU-A',
          status: 'AVAILABLE',
          isolation_capable: true,
        }],
      });
    }
    if (url.endsWith('/allocation/recommend')) {
      return recommendationHandler(JSON.parse(String(init?.body)) as {
        patient_id: string;
        algorithm: string;
      });
    }
    if (url.endsWith('/allocation/approve')) {
      return response({ patient_id: 'PAT-001', bed_id: 'ICU-01', status: 'APPROVED' });
    }
    throw new Error(`Unexpected request: ${url}`);
  });
  globalThis.fetch = fetchMock as typeof fetch;
  return fetchMock;
}

function mockRejectionApi(
  rejectionHandler: (body: { recommendation_id: number; reason: string }) => Promise<Response>,
) {
  const fetchMock = vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
    const url = String(input);
    if (url.endsWith('/beds')) return response({ beds: [] });
    if (url.endsWith('/allocation/recommend')) return response(ruleBasedRecommendation());
    if (url.endsWith('/allocation/approve')) {
      return response({ patient_id: 'PAT-001', bed_id: 'ICU-01', status: 'APPROVED' });
    }
    if (url.endsWith('/allocation/reject')) {
      return rejectionHandler(JSON.parse(String(init?.body)) as {
        recommendation_id: number;
        reason: string;
      });
    }
    throw new Error(`Unexpected request: ${url}`);
  });
  globalThis.fetch = fetchMock as typeof fetch;
  return fetchMock;
}

describe('RecommendationDrawer algorithm selection', () => {
  beforeEach(() => {
    vi.restoreAllMocks();
    sessionStorage.clear();
  });

  it('defaults to Rule-Based and sends that algorithm', async () => {
    const calls: Array<{ patient_id: string; algorithm: string }> = [];
    mockApi(async (body) => {
      calls.push(body);
      return response(ruleBasedRecommendation());
    });

    renderDrawer();

    expect((screen.getByLabelText('Recommendation algorithm') as HTMLSelectElement).value)
      .toBe('rule_based');
    await screen.findByText('Generated by: Rule-Based');
    expect(calls[0]).toEqual({ patient_id: 'PAT-001', algorithm: 'rule_based' });
  });

  it('fetches a fresh DQN recommendation and does not show the old result while loading', async () => {
    const calls: Array<{ patient_id: string; algorithm: string }> = [];
    let finishDqn: ((result: Response) => void) | undefined;
    mockApi(async (body) => {
      calls.push(body);
      if (body.algorithm === 'dqn_safe') {
        return new Promise<Response>((resolve) => {
          finishDqn = resolve;
        });
      }
      return response(ruleBasedRecommendation());
    });

    renderDrawer();
    await screen.findByText('Compatible ICU bed available');

    fireEvent.change(screen.getByLabelText('Recommendation algorithm'), {
      target: { value: 'dqn_safe' },
    });

    await waitFor(() => {
      expect(calls[1]).toEqual({ patient_id: 'PAT-001', algorithm: 'dqn_safe' });
    });
    expect(screen.queryByText('Compatible ICU bed available')).toBeNull();
    expect(await screen.findByText('Loading DQN Safe recommendation...')).toBeTruthy();

    finishDqn?.(response(dqnRecommendation()));
    expect(await screen.findByText('DQN Safe decision details')).toBeTruthy();
    expect(screen.getByText('Safety intervention applied')).toBeTruthy();
    expect(screen.getAllByText('Step-down').length).toBeGreaterThan(0);
    expect(screen.getByText('4.3 days')).toBeTruthy();
    expect(screen.getByText('0.7000')).toBeTruthy();
  });

  it('retries with the currently selected algorithm', async () => {
    const calls: Array<{ patient_id: string; algorithm: string }> = [];
    let dqnCalls = 0;
    mockApi(async (body) => {
      calls.push(body);
      if (body.algorithm === 'dqn_safe' && dqnCalls++ === 0) {
        return response({ detail: 'DQN unavailable' }, 503);
      }
      return response(body.algorithm === 'dqn_safe'
        ? dqnRecommendation()
        : ruleBasedRecommendation());
    });

    renderDrawer();
    await screen.findByText('Generated by: Rule-Based');
    fireEvent.change(screen.getByLabelText('Recommendation algorithm'), {
      target: { value: 'dqn_safe' },
    });
    await screen.findByText('DQN unavailable');

    fireEvent.click(screen.getByRole('button', { name: 'Retry' }));

    await screen.findByText('DQN Safe decision details');
    expect(calls.map((call) => call.algorithm)).toEqual([
      'rule_based', 'dqn_safe', 'dqn_safe',
    ]);
  });

  it('approves the exact Rule-Based recommendation returned by the backend', async () => {
    const calls: Array<{ url: string; body?: string }> = [];
    const fetchMock = vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
      const url = String(input);
      calls.push({ url, body: init?.body?.toString() });
      if (url.endsWith('/beds')) return response({ beds: [] });
      if (url.endsWith('/allocation/recommend')) {
        const request = JSON.parse(String(init?.body)) as { algorithm: string };
        return response(request.algorithm === 'dqn_safe'
          ? dqnRecommendation()
          : ruleBasedRecommendation());
      }
      if (url.endsWith('/allocation/approve')) {
        return response({ patient_id: 'PAT-001', bed_id: 'ICU-01', status: 'APPROVED' });
      }
      throw new Error(`Unexpected request: ${url}`);
    });
    globalThis.fetch = fetchMock as typeof fetch;

    renderDrawer();
    await screen.findByText('Generated by: Rule-Based');
    expect(screen.getAllByText(/Recommendation #501/).length).toBeGreaterThan(0);
    fireEvent.click(screen.getByRole('button', { name: 'Approve Allocation' }));

    await waitFor(() => {
      const approval = calls.find((call) => call.url.endsWith('/allocation/approve'));
      expect(approval).toBeDefined();
      expect(JSON.parse(approval?.body ?? '{}')).toEqual({ recommendation_id: 501 });
    });
  });

  it('approves DQN Safe using its persisted recommendation ID', async () => {
    const calls: Array<{ url: string; body?: string }> = [];
    const fetchMock = vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
      const url = String(input);
      calls.push({ url, body: init?.body?.toString() });
      if (url.endsWith('/beds')) return response({ beds: [] });
      if (url.endsWith('/allocation/recommend')) {
        const request = JSON.parse(String(init?.body)) as { algorithm: string };
        return response(request.algorithm === 'dqn_safe'
          ? dqnRecommendation()
          : ruleBasedRecommendation());
      }
      if (url.endsWith('/allocation/approve')) {
        return response({ patient_id: 'PAT-001', bed_id: 'ICU-01', status: 'APPROVED' });
      }
      throw new Error(`Unexpected request: ${url}`);
    });
    globalThis.fetch = fetchMock as typeof fetch;

    renderDrawer();
    await screen.findByText('Generated by: Rule-Based');
    fireEvent.change(screen.getByLabelText('Recommendation algorithm'), {
      target: { value: 'dqn_safe' },
    });
    await screen.findByText('DQN Safe decision details');
    fireEvent.click(screen.getByRole('button', { name: 'Approve Allocation' }));

    await waitFor(() => {
      const approval = calls.find((call) => call.url.endsWith('/allocation/approve'));
      expect(approval).toBeDefined();
      expect(JSON.parse(approval?.body ?? '{}')).toEqual({ recommendation_id: 502 });
    });
  });

  it('does not allow approval when recommendation ID is missing', async () => {
    mockApi(async () => {
      return response({
        patient_id: 'PAT-001',
        recommended_bed_id: 'ICU-01',
        algorithm: 'rule_based',
        reason: 'Compatible ICU bed available',
        status: 'RECOMMENDED',
      });
    });

    renderDrawer();
    await screen.findByText('Failed to fetch recommendation');
    expect((screen.getByRole('button', { name: 'Approve Allocation' }) as HTMLButtonElement).disabled)
      .toBe(true);
  });

  it('shows a clear message when the backend rejects an approval', async () => {
    let recommendationId = 0;
    const fetchMock = vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
      const url = String(input);
      if (url.endsWith('/beds')) return response({ beds: [] });
      if (url.endsWith('/allocation/recommend')) return response(ruleBasedRecommendation());
      if (url.endsWith('/allocation/approve')) {
        recommendationId = (JSON.parse(String(init?.body)) as { recommendation_id: number }).recommendation_id;
        return response({ detail: 'Bed is not available' }, 409);
      }
      throw new Error(`Unexpected request: ${url}`);
    });
    globalThis.fetch = fetchMock as typeof fetch;

    renderDrawer();
    await screen.findByText('Generated by: Rule-Based');
    fireEvent.click(screen.getByRole('button', { name: 'Approve Allocation' }));

    expect(await screen.findAllByText(/A required resource is no longer available/)).not.toHaveLength(0);
    expect(recommendationId).toBe(501);
  });

  it.each([
    {
      algorithm: 'rule_based',
      detail: 'Recommendation has already been decided',
      expected: /expired or was already decided/,
    },
    {
      algorithm: 'rule_based',
      detail: 'Encounter is no longer waiting for allocation',
      expected: /patient or admission is no longer eligible/,
    },
    {
      algorithm: 'dqn_safe',
      detail: 'DQN recommendation failed current safety validation',
      expected: /DQN safety validation failed/,
    },
  ])('explains stale or unsafe approval failure for $algorithm', async ({ algorithm, detail, expected }) => {
    const fetchMock = vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
      const url = String(input);
      if (url.endsWith('/beds')) return response({ beds: [] });
      if (url.endsWith('/allocation/recommend')) {
        const request = JSON.parse(String(init?.body)) as { algorithm: string };
        return response(request.algorithm === 'dqn_safe'
          ? dqnRecommendation()
          : ruleBasedRecommendation());
      }
      if (url.endsWith('/allocation/approve')) return response({ detail }, 409);
      throw new Error(`Unexpected request: ${url}`);
    });
    globalThis.fetch = fetchMock as typeof fetch;

    renderDrawer();
    await screen.findByText('Generated by: Rule-Based');
    if (algorithm === 'dqn_safe') {
      fireEvent.change(screen.getByLabelText('Recommendation algorithm'), {
        target: { value: 'dqn_safe' },
      });
      await screen.findByText('DQN Safe decision details');
    }
    fireEvent.click(screen.getByRole('button', { name: 'Approve Allocation' }));
    expect(await screen.findAllByText(expected)).not.toHaveLength(0);
  });

  it('prevents duplicate approval submissions while the request is pending', async () => {
    const approvalCalls: Array<{ recommendation_id: number }> = [];
    let finishApproval: ((result: Response) => void) | undefined;
    const fetchMock = vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
      const url = String(input);
      if (url.endsWith('/beds')) return response({ beds: [] });
      if (url.endsWith('/allocation/recommend')) return response(ruleBasedRecommendation());
      if (url.endsWith('/allocation/approve')) {
        approvalCalls.push(JSON.parse(String(init?.body)) as { recommendation_id: number });
        return new Promise<Response>((resolve) => { finishApproval = resolve; });
      }
      throw new Error(`Unexpected request: ${url}`);
    });
    globalThis.fetch = fetchMock as typeof fetch;

    renderDrawer();
    await screen.findByText('Generated by: Rule-Based');
    const approveButton = screen.getByRole('button', { name: 'Approve Allocation' });
    fireEvent.click(approveButton);
    await waitFor(() => expect(approvalCalls).toHaveLength(1));
    expect((approveButton as HTMLButtonElement).disabled).toBe(true);
    fireEvent.click(approveButton);
    expect(approvalCalls).toHaveLength(1);

    finishApproval?.(response({ patient_id: 'PAT-001', bed_id: 'ICU-01', status: 'APPROVED' }));
    await screen.findByText(/successfully allocated to Bed ICU-01/);
  });

  it('shows safe unavailable labels when optional DQN detail fields are missing', async () => {
    mockApi(async (body) => response(body.algorithm === 'dqn_safe'
      ? {
          recommendation_id: 503,
          patient_id: 'PAT-001',
          recommended_bed_id: null,
          algorithm: 'dqn_safe',
          reason: 'Policy selected WAIT',
          status: 'WAIT',
        }
      : ruleBasedRecommendation()));

    renderDrawer();
    await screen.findByText('Generated by: Rule-Based');
    fireEvent.change(screen.getByLabelText('Recommendation algorithm'), {
      target: { value: 'dqn_safe' },
    });

    expect(await screen.findByText('DQN Safe decision details')).toBeTruthy();
    expect(screen.getByText('Safety information unavailable')).toBeTruthy();
    expect(screen.getByText('Q-values not provided.')).toBeTruthy();
    expect(screen.getAllByText('Not provided').length).toBeGreaterThan(0);
  });

  it('rejects the exact persisted recommendation with the entered reason and keeps its details visible', async () => {
    const calls: Array<{ recommendation_id: number; reason: string }> = [];
    mockRejectionApi(async (body) => {
      calls.push(body);
      return response({
        recommendation_id: 501,
        patient_id: 'PAT-001',
        status: 'REJECTED',
        reason: 'Clinical contraindication',
      });
    });

    renderDrawer();
    await screen.findByText('Generated by: Rule-Based');
    const rejectButton = screen.getByRole('button', { name: 'Reject Recommendation' });
    expect((rejectButton as HTMLButtonElement).disabled).toBe(true);
    fireEvent.change(screen.getByLabelText('Rejection reason'), {
      target: { value: '  Clinical contraindication  ' },
    });
    expect((rejectButton as HTMLButtonElement).disabled).toBe(false);
    fireEvent.click(rejectButton);

    await screen.findByRole('status');
    expect(calls).toEqual([{
      recommendation_id: 501,
      reason: 'Clinical contraindication',
    }]);
    expect(screen.getAllByText(/Recommendation #501/).length).toBeGreaterThan(0);
    expect(screen.getByText('Compatible ICU bed available')).toBeTruthy();
    expect(screen.getByText(/original recommendation details remain available/i)).toBeTruthy();
  });

  it('requires a nonblank backend-valid reason before enabling rejection', async () => {
    mockRejectionApi(async () => response({
      recommendation_id: 501,
      patient_id: 'PAT-001',
      status: 'REJECTED',
      reason: 'Valid reason',
    }));

    renderDrawer();
    await screen.findByText('Generated by: Rule-Based');
    const reason = screen.getByLabelText('Rejection reason');
    const rejectButton = screen.getByRole('button', { name: 'Reject Recommendation' });
    expect((rejectButton as HTMLButtonElement).disabled).toBe(true);

    fireEvent.change(reason, { target: { value: '   ' } });
    expect((rejectButton as HTMLButtonElement).disabled).toBe(true);
    fireEvent.change(reason, { target: { value: 'No' } });
    expect((rejectButton as HTMLButtonElement).disabled).toBe(true);
    fireEvent.change(reason, { target: { value: 'Valid reason' } });
    expect((rejectButton as HTMLButtonElement).disabled).toBe(false);
  });

  it('disables rejection for a recommendation with no suitable bed', async () => {
    mockApi(async () => response({
      recommendation_id: 504,
      patient_id: 'PAT-001',
      recommended_bed_id: null,
      algorithm: 'rule_based',
      reason: 'No compatible bed available',
      status: 'NO_SUITABLE_BED',
    }));

    renderDrawer();
    await screen.findByText('No Suitable Bed Available');
    expect((screen.getByRole('button', { name: 'Reject Recommendation' }) as HTMLButtonElement).disabled)
      .toBe(true);
    expect((screen.getByLabelText('Rejection reason') as HTMLTextAreaElement).disabled).toBe(true);
  });

  it('prevents duplicate rejection and disables approval while rejection is pending', async () => {
    const calls: Array<{ recommendation_id: number; reason: string }> = [];
    let finishRejection: ((result: Response) => void) | undefined;
    mockRejectionApi((body) => {
      calls.push(body);
      return new Promise<Response>((resolve) => { finishRejection = resolve; });
    });

    renderDrawer();
    await screen.findByText('Generated by: Rule-Based');
    fireEvent.change(screen.getByLabelText('Rejection reason'), {
      target: { value: 'Clinical contraindication' },
    });
    const rejectButton = screen.getByRole('button', { name: 'Reject Recommendation' });
    fireEvent.click(rejectButton);
    await waitFor(() => expect(calls).toHaveLength(1));
    expect((rejectButton as HTMLButtonElement).disabled).toBe(true);
    expect((screen.getByRole('button', { name: 'Approve Allocation' }) as HTMLButtonElement).disabled)
      .toBe(true);
    fireEvent.click(rejectButton);
    expect(calls).toHaveLength(1);

    finishRejection?.(response({
      recommendation_id: 501,
      patient_id: 'PAT-001',
      status: 'REJECTED',
      reason: 'Clinical contraindication',
    }));
    await screen.findByRole('status');
  });

  it.each([
    {
      detail: 'Recommendation has already been decided',
      expected: /already decided/i,
    },
    {
      detail: 'Recommendation not found',
      expected: /could not be found/i,
    },
    {
      detail: 'Patient is not waiting for allocation',
      expected: /no longer eligible for rejection/i,
    },
    {
      detail: 'Rejection service unavailable',
      expected: /Rejection service unavailable/i,
    },
  ])('shows an actionable rejection error for "$detail"', async ({ detail, expected }) => {
    mockRejectionApi(async () => response({ detail }, detail === 'Recommendation not found' ? 404 : 409));

    renderDrawer();
    await screen.findByText('Generated by: Rule-Based');
    fireEvent.change(screen.getByLabelText('Rejection reason'), {
      target: { value: 'Clinical contraindication' },
    });
    fireEvent.click(screen.getByRole('button', { name: 'Reject Recommendation' }));
    expect(await screen.findAllByText(expected)).not.toHaveLength(0);
  });
});
